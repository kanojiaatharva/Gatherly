package com.gatherly.ai;

import com.gatherly.budget.BudgetItem;
import com.gatherly.budget.BudgetItemRepository;
import com.gatherly.common.BadRequestException;
import com.gatherly.events.Event;
import com.gatherly.events.OwnershipService;
import com.gatherly.tasks.Task;
import com.gatherly.tasks.TaskRepository;
import java.util.List;
import java.util.Optional;
import com.gatherly.common.RateLimiterService;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

@Service
public class AiPlannerService {

    private final AiPlanningProvider aiPlanningProvider;
    private final BudgetItemRepository budgetItemRepository;
    private final TaskRepository taskRepository;
    private final PlanRevisionRepository planRevisionRepository;
    private final OwnershipService ownershipService;
    private final RateLimiterService rateLimiterService;

    public AiPlannerService(
            AiPlanningProvider aiPlanningProvider,
            BudgetItemRepository budgetItemRepository,
            TaskRepository taskRepository,
            PlanRevisionRepository planRevisionRepository,
            OwnershipService ownershipService,
            RateLimiterService rateLimiterService) {
        this.aiPlanningProvider = aiPlanningProvider;
        this.budgetItemRepository = budgetItemRepository;
        this.taskRepository = taskRepository;
        this.planRevisionRepository = planRevisionRepository;
        this.ownershipService = ownershipService;
        this.rateLimiterService = rateLimiterService;
    }

    @Transactional
    public GeneratedPlanResponse generatePlan(Long eventId, Long userId, String promptNotes) {
        rateLimiterService.checkLimit("user-" + userId);
        Event event = ownershipService.verifyAndGetEvent(eventId, userId);

        GeneratedPlanResponse plan = aiPlanningProvider.generatePlan(event, promptNotes);

        List<BudgetItem> existingBudget = budgetItemRepository.findByEventIdOrderByCreatedAtAsc(eventId);
        List<Task> existingTasks = taskRepository.findByEventIdOrderByDueDateAscCreatedAtAsc(eventId);

        // Save generated budget items (skip if category already exists)
        for (GeneratedBudgetItem item : plan.budgetItems()) {
            boolean categoryExists = existingBudget.stream()
                    .anyMatch(b -> b.getCategory().equalsIgnoreCase(item.category()));
            if (!categoryExists) {
                BudgetItem entity = new BudgetItem(
                        event,
                        item.category(),
                        item.description(),
                        item.estimatedAmount(),
                        null,
                        true
                );
                budgetItemRepository.save(entity);
            }
        }

        // Save generated tasks (skip if title already exists)
        for (GeneratedTask t : plan.tasks()) {
            boolean taskExists = existingTasks.stream()
                    .anyMatch(existing -> existing.getTitle().equalsIgnoreCase(t.title()));
            if (!taskExists) {
                Task task = new Task(
                        event,
                        t.title(),
                        t.description(),
                        t.dueDate(),
                        "TODO",
                        t.priority() != null ? t.priority() : "MEDIUM",
                        t.assigneeLabel()
                );
                taskRepository.save(task);
            }
        }

        // Record initial revision
        Optional<PlanRevision> topRev = planRevisionRepository.findTopByEventIdOrderByVersionNumberDesc(eventId);
        int nextVersion = topRev.map(r -> r.getVersionNumber() + 1).orElse(1);
        PlanRevision revision = new PlanRevision(event, nextVersion, "Initial plan generated by Gatherly AI assistant.");
        planRevisionRepository.save(revision);

        return plan;
    }

    @Transactional(readOnly = true)
    public PlanRevisionProposal proposeRevision(Long eventId, Long userId, PlanRevisionRequest request) {
        rateLimiterService.checkLimit("user-" + userId);
        Event event = ownershipService.verifyAndGetEvent(eventId, userId);
        List<BudgetItem> currentBudget = budgetItemRepository.findByEventIdOrderByCreatedAtAsc(eventId);
        List<Task> currentTasks = taskRepository.findByEventIdOrderByDueDateAscCreatedAtAsc(eventId);

        return aiPlanningProvider.proposeRevision(event, currentBudget, currentTasks, request.prompt());
    }

    @Transactional
    public PlanRevisionResponse applyRevision(Long eventId, Long userId, ApplyRevisionRequest request) {
        Event event = ownershipService.verifyAndGetEvent(eventId, userId);
        PlanRevisionProposal proposal = request.proposal();

        if (proposal == null) {
            throw new BadRequestException("Proposal cannot be null");
        }

        // Apply budget adjustments with validation and preservation of confirmed items
        if (proposal.budgetAdjustments() != null) {
            List<BudgetItem> currentBudget = budgetItemRepository.findByEventIdOrderByCreatedAtAsc(eventId);
            for (ProposedBudgetItemDiff diff : proposal.budgetAdjustments()) {
                if (diff.newAmount() != null && diff.newAmount().compareTo(java.math.BigDecimal.ZERO) < 0) {
                    throw new BadRequestException("Budget amount cannot be negative: " + diff.newAmount());
                }

                if ("ADD".equalsIgnoreCase(diff.action())) {
                    BudgetItem newItem = new BudgetItem(
                            event,
                            diff.category(),
                            diff.description() != null ? diff.description() : "Proposed allocation",
                            diff.newAmount() != null ? diff.newAmount() : java.math.BigDecimal.ZERO,
                            null,
                            true
                    );
                    budgetItemRepository.save(newItem);
                } else if ("UPDATE".equalsIgnoreCase(diff.action())) {
                    Optional<BudgetItem> match = currentBudget.stream()
                            .filter(b -> b.getCategory().equalsIgnoreCase(diff.category()))
                            .findFirst();
                    if (match.isPresent()) {
                        BudgetItem item = match.get();
                        // Preserve manual actual amounts and confirmation state
                        item.setEstimatedAmount(diff.newAmount() != null ? diff.newAmount() : java.math.BigDecimal.ZERO);
                        if (diff.description() != null && !diff.description().isBlank()) {
                            item.setDescription(diff.description());
                        }
                        budgetItemRepository.save(item);
                    } else {
                        BudgetItem newItem = new BudgetItem(
                                event,
                                diff.category(),
                                diff.description(),
                                diff.newAmount() != null ? diff.newAmount() : java.math.BigDecimal.ZERO,
                                null,
                                true
                        );
                        budgetItemRepository.save(newItem);
                    }
                } else if ("REMOVE".equalsIgnoreCase(diff.action())) {
                    Optional<BudgetItem> match = currentBudget.stream()
                            .filter(b -> b.getCategory().equalsIgnoreCase(diff.category()))
                            .findFirst();
                    if (match.isPresent()) {
                        BudgetItem item = match.get();
                        // Strictly preserve manual/confirmed items from deletion
                        boolean isManual = Boolean.FALSE.equals(item.getIsEstimate()) || item.getActualAmount() != null;
                        if (!isManual) {
                            budgetItemRepository.delete(item);
                        }
                    }
                }
            }
        }

        // Apply task adjustments with preservation of completed tasks
        if (proposal.taskAdjustments() != null) {
            List<Task> currentTasks = taskRepository.findByEventIdOrderByDueDateAscCreatedAtAsc(eventId);
            for (ProposedTaskDiff diff : proposal.taskAdjustments()) {
                if ("ADD".equalsIgnoreCase(diff.action())) {
                    boolean alreadyExists = currentTasks.stream()
                            .anyMatch(t -> t.getTitle().equalsIgnoreCase(diff.title()));
                    if (!alreadyExists) {
                        Task newTask = new Task(
                                event,
                                diff.title(),
                                diff.description(),
                                diff.dueDate(),
                                "TODO",
                                diff.priority() != null ? diff.priority() : "MEDIUM",
                                "Host"
                        );
                        taskRepository.save(newTask);
                    }
                } else if ("UPDATE".equalsIgnoreCase(diff.action())) {
                    Optional<Task> match = currentTasks.stream()
                            .filter(t -> t.getTitle().equalsIgnoreCase(diff.title()))
                            .findFirst();
                    if (match.isPresent()) {
                        Task task = match.get();
                        // Do not overwrite completed tasks back to TODO
                        if (!"COMPLETED".equalsIgnoreCase(task.getStatus())) {
                            if (diff.description() != null) task.setDescription(diff.description());
                            if (diff.dueDate() != null) task.setDueDate(diff.dueDate());
                            if (diff.priority() != null) task.setPriority(diff.priority());
                            taskRepository.save(task);
                        }
                    }
                }
            }
        }

        // Record revision history
        Optional<PlanRevision> topRev = planRevisionRepository.findTopByEventIdOrderByVersionNumberDesc(eventId);
        int nextVersion = topRev.map(r -> r.getVersionNumber() + 1).orElse(1);

        String summary = proposal.changeSummary() != null && !proposal.changeSummary().isBlank()
                ? proposal.changeSummary()
                : "Revised plan based on user prompt: " + proposal.prompt();

        PlanRevision revision = new PlanRevision(event, nextVersion, summary);
        PlanRevision saved = planRevisionRepository.save(revision);

        return PlanRevisionResponse.fromEntity(saved);
    }

    @Transactional(readOnly = true)
    public List<PlanRevisionResponse> getRevisions(Long eventId, Long userId) {
        ownershipService.verifyAndGetEvent(eventId, userId);
        return planRevisionRepository.findByEventIdOrderByVersionNumberDesc(eventId)
                .stream()
                .map(PlanRevisionResponse::fromEntity)
                .toList();
    }
}
